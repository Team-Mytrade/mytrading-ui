interface ReceiptAllocation {
  id?: number;
  invoiceId: number;
  invoiceNumber?: string;
  allocatedAmount?: number;
  invoiceGrandTotal?: number;
  invoiceAmountPaid?: number;
  invoiceBalance?: number;
  invoiceStatus?: string;
}


const RECEIPT_STATUS_TONES: Record<string, string> = {
  POSTED: "bg-emerald-50 text-emerald-700 border-emerald-200",
  REVERSED: "bg-gray-100 text-gray-500 border-gray-200 line-through",
};

interface Allocation {
  id: number;
  /** Generated by the backend. */
  receiptNumber?: string;
  paymentDate?: string;
  customerId?: number;
  totalAmountReceived?: number;
  totalAllocated?: number;
  unallocatedAmount?: number;
  paymentMethod?: string;
  referenceNumber?: string;
  /** Set by the backend (the signed-in user). */
  receivedBy?: string;
  notes?: string;
  allocations?: ReceiptAllocation[];
  createdDate?: string;
  status?: string;
  reversedAt?: string;
  reversedBy?: string;
  reversalReason?: string;
  // Filled for the table, search and export (receipts only carry customerId)
  customerName?: string;
}

/** Body of POST /receipts. receiptNumber and receivedBy are set by the backend. */
interface CreateReceiptPayload {
  customerId: number;
  paymentDate: string;
  totalAmountReceived: number;
  paymentMethod: string;
  referenceNumber?: string;
  notes?: string;
  allocations: { invoiceId: number; allocatedAmount: number }[];
}

/** Shape of GET /receipts/reversible (note: paymentReceiptId, not id). */
interface ReversibleReceipt {
  paymentReceiptId: number;
}

/** Fields used from the sales invoices list / outstanding API. */
interface InvoiceRow {
  id: number;
  invoiceNumber?: string;
  invoiceDate?: string;
  dueDate?: string;
  customerId?: number;
  customerCode?: string;
  customerName?: string;
  grandTotal?: number;
  balanceAmount?: number;
}

type ReceiptForm = {
  customerId?: string;
  paymentDate?: string;
  totalAmountReceived?: string;
  paymentMethod?: string;
  referenceNumber?: string;
  notes?: string;
};


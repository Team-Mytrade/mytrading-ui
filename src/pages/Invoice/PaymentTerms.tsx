import React, { useEffect, useState, ChangeEvent, FormEvent } from "react";
import axios from "axios";
import { PencilSquareIcon, TrashIcon, ClockIcon } from "@heroicons/react/24/outline";
import PageMeta from "../../components/common/PageMeta";
import PageBreadcrumb from "../../components/common/PageBreadCrumb";
import { ToasterService } from "../../Services/ToasterService";
import DynamicPopup from "../../components/common/Popup";
import Dragger from "../../components/common/Dragger";
import StatsCardFilter, { StatsCardOption, useStatsCardFilter } from "../../components/common/StatsCardFilter";
import { AddButton } from "../../components/common/AddButton";
import { ICON_BUTTON_CLASS } from "../../components/common/CloseButton";
import ReusableTable, { ColumnDef } from "../../components/common/Table";
import { FloatingInput } from "../../components/inputfeild/FloatingInput";
import { usePermissions } from "../../access/usePermissions";

interface PaymentTerm {
  id: number;
  termCode?: string;
  description?: string;
  dueDays?: number;
}

/**
 * Fields the user edits. termCode is generated by the backend on create,
 * so it is never typed in by the user.
 */
interface PaymentTermPayload {
  termCode?: string;
  description: string;
  dueDays: number;
}

const API_URL = "/v1/api/invoice/payment-terms";
const PAGE_SIZE = 10;
const MAX_DUE_DAYS = 365;

/** Clickable stats cards: click one to show only those rows, click again to show all. */
const STATS_CARDS: StatsCardOption<PaymentTerm>[] = [
  { key: "ALL", label: "Total Terms", match: () => true, tone: "cyan" },
  { key: "SHORT", label: "Up to 30 Days", match: (t) => Number(t.dueDays ?? 0) <= 30, tone: "green" },
  { key: "LONG", label: "More than 30 Days", match: (t) => Number(t.dueDays ?? 0) > 30, tone: "amber" },
];

/** 0 → "Immediate", 1 → "1 day", 30 → "30 days" */
const formatDueDays = (days?: number) => {
  if (days == null || (days as unknown) === "") return "--";
  const value = Number(days);
  if (value === 0) return "Immediate";
  return `${value} ${value === 1 ? "day" : "days"}`;
};

/** Looks like a disabled input (same height, border and floating label). Used for the backend-generated code. */
const ReadOnlyField = ({ label, value }: { label: string; value?: string }) => (
  <div style={{ position: "relative", marginBottom: "20px", width: "100%" }}>
    <div
      className="flex h-[52px] cursor-default items-center rounded-md border border-gray-300 bg-gray-50 px-3 pt-3 text-base text-gray-700 dark:border-gray-700 dark:bg-gray-800 dark:text-gray-200"
      aria-readonly="true"
    >
      <span className="truncate">{value || ""}</span>
    </div>
    <span className="pointer-events-none absolute left-3 top-0 -translate-y-1/2 bg-white px-1 text-xs font-medium text-gray-500 dark:bg-gray-900 dark:text-gray-400">
      {label}
    </span>
  </div>
);

const PaymentTerms: React.FC = () => {
  const { canCreate, canUpdate, canDelete } = usePermissions();

  const [paymentTerms, setPaymentTerms] = useState<PaymentTerm[]>([]);
  const [form, setForm] = useState<Partial<PaymentTerm>>({});
  const [editingId, setEditingId] = useState<number | null>(null);
  const [showFormModal, setShowFormModal] = useState(false);
  const [showDeletePopup, setShowDeletePopup] = useState(false);
  const [termToDelete, setTermToDelete] = useState<PaymentTerm | null>(null);
  const [submitting, setSubmitting] = useState(false);
  const [deleting, setDeleting] = useState(false);
  const [isLoading, setIsLoading] = useState(false);

  const { filteredRows, cardFilterProps, selected } = useStatsCardFilter(paymentTerms, STATS_CARDS);

  useEffect(() => {
    fetchPaymentTerms();
    // Toolbar Refresh icon reloads the list
    const reload = () => fetchPaymentTerms();
    window.addEventListener("reusable-table:refresh", reload);
    return () => window.removeEventListener("reusable-table:refresh", reload);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const fetchPaymentTerms = async () => {
    try {
      setIsLoading(true);
      const res = await axios.get<PaymentTerm[]>(API_URL);
      setPaymentTerms(Array.isArray(res.data) ? res.data : []);
    } catch (err) {
      console.error("Error fetching payment terms", err);
      ToasterService.error("Failed to load payment terms");
      setPaymentTerms([]);
    } finally {
      setIsLoading(false);
    }
  };

  const handleChange = (e: ChangeEvent<HTMLInputElement>) =>
    setForm({ ...form, [e.target.name]: e.target.value });

  const handleSubmit = async (e: FormEvent) => {
    e.preventDefault();

    const description = form.description?.trim() || "";
    if (!description) {
      ToasterService.error("Description is required");
      return;
    }

    const dueDaysText = String(form.dueDays ?? "").trim();
    if (dueDaysText === "") {
      ToasterService.error("Due days is required");
      return;
    }
    const dueDays = Number(dueDaysText);
    if (!Number.isInteger(dueDays) || dueDays < 0) {
      ToasterService.error("Due days must be a whole number (0 or more)");
      return;
    }
    if (dueDays > MAX_DUE_DAYS) {
      ToasterService.error(`Due days can be at most ${MAX_DUE_DAYS}`);
      return;
    }

    const payload: PaymentTermPayload = {
      description,
      dueDays,
      // Create: no code, the backend generates it. Edit: send the existing code back unchanged.
      ...(editingId !== null && form.termCode ? { termCode: form.termCode } : {}),
    };

    setSubmitting(true);
    try {
      const res =
        editingId !== null
          ? await axios.put(`${API_URL}/${editingId}`, payload)
          : await axios.post(API_URL, payload);
      if (res.status === 200 || res.status === 201) {
        ToasterService.success(
          editingId !== null
            ? "Payment term updated successfully!"
            : `Payment term ${res.data?.termCode ? `${res.data.termCode} ` : ""}added successfully!`
        );
        setShowFormModal(false);
        setForm({});
        setEditingId(null);
        await fetchPaymentTerms();
      }
    } catch (err: any) {
      console.error("Error submitting payment term", err);
      ToasterService.error(err?.response?.data?.message || "Failed to save payment term");
    } finally {
      setSubmitting(false);
    }
  };

  const handleEdit = (term: PaymentTerm) => {
    setForm(term);
    setEditingId(term.id);
    setShowFormModal(true);
  };

  const openCreate = () => {
    setShowFormModal(true);
    setForm({});
    setEditingId(null);
  };

  const closeModal = () => {
    setShowFormModal(false);
    setEditingId(null);
    setForm({});
  };

  const handleDelete = (term: PaymentTerm) => {
    setTermToDelete(term);
    setShowDeletePopup(true);
  };

  const confirmDelete = async () => {
    if (!termToDelete || deleting) return;
    setDeleting(true);
    try {
      await axios.delete(`${API_URL}/${termToDelete.id}`);
      ToasterService.success("Payment term deleted successfully!");
      setShowDeletePopup(false);
      setTermToDelete(null);
      fetchPaymentTerms();
    } catch (err: any) {
      console.error("Error deleting payment term", err);
      // A term used by invoices usually cannot be deleted
      ToasterService.error(
        err?.response?.status === 409
          ? "This payment term is used by other records, so it cannot be deleted."
          : "Failed to delete payment term"
      );
    } finally {
      setDeleting(false);
    }
  };

  const tableColumns: ColumnDef<PaymentTerm>[] = [
    {
      key: "termCode",
      label: "Term Code",
      sortable: true,
      headerClassName: "w-[25%] text-left",
      className: "w-[25%]",
      render: (term) => (
        <div className="flex items-center gap-3">
          <div className="h-8 w-8 rounded-xl bg-gradient-to-br from-cyan-500/10 to-blue-500/10 border border-cyan-500/10 flex items-center justify-center flex-shrink-0 shadow-sm">
            <ClockIcon className="h-4 w-4 text-cyan-600" />
          </div>
          <span className="text-sm font-semibold text-slate-900 truncate leading-snug">
            {term.termCode || "--"}
          </span>
        </div>
      ),
    },
    {
      key: "description",
      label: "Description",
      sortable: true,
      headerClassName: "w-[45%] text-left",
      className: "w-[45%]",
      render: (term) => (
        <span className="text-sm text-slate-600 truncate" title={term.description}>
          {term.description || "--"}
        </span>
      ),
    },
    {
      key: "dueDays",
      label: "Due Days",
      sortable: true,
      headerClassName: "w-[15%] text-left",
      className: "w-[15%]",
      sortValueGetter: (term) => Number(term.dueDays ?? 0),
      detailFormatter: (term) => formatDueDays(term.dueDays),
      exportValueGetter: (term) => formatDueDays(term.dueDays),
      render: (term) => (
        <span className="inline-flex items-center px-2.5 py-0.5 text-xs font-semibold rounded-full bg-blue-50 text-blue-700 border border-blue-200/40">
          {formatDueDays(term.dueDays)}
        </span>
      ),
    },
    {
      key: "actions",
      label: "Actions",
      sortable: false,
      headerClassName: "w-[15%] text-right pr-4",
      className: "w-[15%] text-right",
      render: (term) => (
        <div className="flex items-center justify-end gap-0.5">
          {canUpdate && (
            <button
              type="button"
              onClick={() => handleEdit(term)}
              className="rounded-lg p-1.5 text-slate-400 transition-all hover:bg-cyan-50 hover:text-cyan-600"
              title="Edit Payment Term"
            >
              <PencilSquareIcon className="h-4 w-4" />
            </button>
          )}
          {canDelete && (
            <button
              type="button"
              onClick={() => handleDelete(term)}
              className="rounded-lg p-1.5 text-slate-400 transition-all hover:bg-red-50 hover:text-red-600"
              title="Delete Payment Term"
            >
              <TrashIcon className="h-4 w-4" />
            </button>
          )}
        </div>
      ),
    },
  ];

  return (
    <>
      <PageMeta title="Payment Terms" description="Manage payment terms" />
      {/* Same layout as the Purchase module pages: Add button sits in the breadcrumb row */}
      <PageBreadcrumb
        className="mr-4"
        pageTitle="Payment Terms"
        actions={canCreate ? <AddButton className="-mr-5" label="Add Payment Term" onClick={openCreate} /> : undefined}
      />

      <div className="w-full max-w-none px-0">
        <div className="px-3">
          {/* Clickable cards + toolbar (columns, export, search, filter, refresh) */}
          <StatsCardFilter {...cardFilterProps} />

          <ReusableTable
            data={filteredRows}
            columns={tableColumns}
            pageSize={PAGE_SIZE}
            defaultSortKey="termCode"
            defaultSortOrder="asc"
            loading={isLoading}
            rowDetailsTitle={(term) => `Payment Term ${term.termCode || ""}`.trim()}
            rowDetailsSubtitle="Payment term details"
            // Hides the details drawer while the edit Dragger is open; it comes back with the saved data
            suspendRowDetails={showFormModal}
            // Edit icon next to ✕ in the row details drawer
            rowDetailsActions={(term: PaymentTerm) =>
              canUpdate ? (
                <button
                  type="button"
                  onClick={() => handleEdit(term)}
                  className={ICON_BUTTON_CLASS}
                  title="Edit"
                  aria-label="Edit this record"
                >
                  <PencilSquareIcon className="h-5 w-5" aria-hidden="true" />
                </button>
              ) : null
            }
            emptyState={
              <div className="flex flex-col items-center justify-center py-12">
                <ClockIcon className="h-12 w-12 text-gray-400 mb-3" />
                <p className="text-gray-500 text-sm mb-2">No payment terms found</p>
                {selected !== "ALL" ? (
                  <p className="text-gray-400 text-xs">Click the selected card again to show all terms</p>
                ) : (
                  canCreate && (
                    <button
                      type="button"
                      onClick={() => openCreate()}
                      className="mt-1 text-cyan-600 hover:text-cyan-700 text-xs font-medium"
                    >
                      Create your first payment term
                    </button>
                  )
                )}
              </div>
            }
          />
        </div>

        <Dragger
          isOpen={showFormModal}
          title={editingId !== null ? "Edit Payment Term" : "Add Payment Term"}
          subtitle={
            editingId !== null
              ? "Update your payment term"
              : "The term code is generated automatically when you save"
          }
          onClose={closeModal}
          onSubmit={handleSubmit}
          submitting={submitting}
          submitLabel={editingId !== null ? "Update" : "Create"}
        >
          <div className="grid grid-cols-1 gap-3 md:grid-cols-2">
            {/* Term code comes from the backend: hidden on Create, read-only on Edit */}
            {editingId !== null && <ReadOnlyField label="Term Code" value={form.termCode} />}
            <FloatingInput
              label="Due Days"
              name="dueDays"
              type="number"
              min={0}
              max={MAX_DUE_DAYS}
              step={1}
              inputMode="numeric"
              value={form.dueDays ?? ""}
              onChange={handleChange}
              // Block keys that make a negative or decimal number
              onKeyDown={(e) => ["e", "E", "+", "-", "."].includes(e.key) && e.preventDefault()}
              // Scrolling over the box must not change the value
              onWheel={(e) => e.currentTarget.blur()}
              required
            />
            <div className={editingId !== null ? "md:col-span-2" : ""}>
              <FloatingInput
                label="Description"
                name="description"
                value={form.description || ""}
                onChange={handleChange}
                maxLength={255}
                required
              />
            </div>
          </div>
        </Dragger>

        <DynamicPopup
          isPopupOpen={showDeletePopup}
          setIsPopupOpen={setShowDeletePopup}
          icon={<TrashIcon className="h-6 w-6 text-red-600" />}
          iconBg="bg-red-100"
          innerText="Delete Payment Term"
          subText={
            termToDelete
              ? `Are you sure you want to delete "${termToDelete.termCode}"? This action cannot be undone.`
              : "Are you sure you want to delete this payment term?"
          }
          confirmLabel={deleting ? "Deleting..." : "Delete"}
          cancelLabel="Cancel"
          onConfirm={confirmDelete}
          onCancel={() => setTermToDelete(null)}
          confirmBtnClass="bg-red-600 hover:bg-red-700 focus:ring-red-500 text-white"
        />
      </div>
    </>
  );
};

export default PaymentTerms;

// ---------- FIFO / FEFO ranks ----------
// Ranked only within the same product AND warehouse. Batches with no date sort last.
const sortTime = (s?: string | null) => parseLocalDate(s)?.getTime() ?? Infinity;

const sameGroup = (a: Batch, b: Batch) =>
  a.productId === b.productId && getWarehouseId(a) === getWarehouseId(b);

const getFIFORank = (batches: Batch[], batch: Batch) =>
  batches
    .filter((b) => sameGroup(b, batch) && (b.quantity || 0) > 0)
    .sort((a, b) => sortTime(a.manufacturingDate) - sortTime(b.manufacturingDate))
    .findIndex((b) => b.id === batch.id) + 1;

// Expired batches are excluded from FEFO, since they shouldn't be picked first.
const getFEFORank = (batches: Batch[], batch: Batch) =>
  batches
    .filter((b) => {
      if (!sameGroup(b, batch) || (b.quantity || 0) <= 0) return false;
      const days = getDaysUntilExpiry(b);
      return days === null || days >= 0;
    })
    .sort((a, b) => sortTime(a.expiryDate) - sortTime(b.expiryDate))
    .findIndex((b) => b.id === batch.id) + 1;

// ---------- Local-only supplier storage (backend has no supplierName field) ----------
function loadSupplierMap(): Record<number, string> {
  try {
    return JSON.parse(localStorage.getItem(SUPPLIER_STORAGE_KEY) || "{}");
  } catch {
    return {};
  }
}

function saveSupplierName(id: number, name: string) {
  const all = loadSupplierMap();
  if (name?.trim()) {
    all[id] = name.trim();
  } else {
    delete all[id];
  }
  try {
    localStorage.setItem(SUPPLIER_STORAGE_KEY, JSON.stringify(all));
  } catch {
    // localStorage can throw in private/incognito modes, so fail silently.
  }
}

function getLocalSupplierName(id: number): string {
  return loadSupplierMap()[id] || "";
}


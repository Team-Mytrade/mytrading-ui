// Parses "YYYY-MM-DD" (or an ISO timestamp) as LOCAL midnight, not UTC, so dates
// don't shift by one day in timezones behind UTC.
const parseLocalDate = (s?: string | null): Date | null => {
  if (!s) return null;
  const [y, m, d] = s.slice(0, 10).split("-").map(Number);
  if (!y || !m || !d) return null;
  return new Date(y, m - 1, d);
};

const fmtDate = (s?: string | null) => {
  const d = parseLocalDate(s);
  return d ? d.toLocaleDateString() : "--";
};

// Returns null when the batch has no expiry date (the API allows null).
const getDaysUntilExpiry = (batch: Pick<Batch, "expiryDate">): number | null => {
  const exp = parseLocalDate(batch.expiryDate);
  if (!exp) return null;
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return Math.round((exp.getTime() - today.getTime()) / 86400000);
};

